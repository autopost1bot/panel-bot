// Longest keys first so "Add account" wins over "Account".
const SORTED: Record<string, [string, string][]> = {};
for (const [lang, dict] of Object.entries(DICT)) {
  SORTED[lang] = Object.entries(dict).sort((a, b) => b[0].length - a[0].length);
}

function applyDict(text: string, lang: string): string {
  const pairs = SORTED[lang];
  if (!pairs) return text;
  const words = PAYMENT_PHRASES[lang as Exclude<Lang, "en">];
  if (words) {
    text = text.replace(/Pay (<b>[^<]+<\/b>) for (\d+) days\?/g, (_, amount, days) => `${words[0]}${amount}${words[1]}${days} ${words[2]}?`);
    text = text.replace(/\b(\d+) (days|min)\b/g, (_, n, unit) => `${n} ${words[unit === "days" ? 2 : 3]}`);
  }
  for (const [from, to] of pairs) {
    if (text.includes(from)) text = text.split(from).join(to);
  }
  return text;
}

/** Translate message HTML. Code blocks, pre blocks and premium emoji tags are
 *  never touched, so keys, usernames and custom emoji survive unchanged. */
export function translateHtml(html: string, lang: string): string {
  if (!html || lang === "en" || !SORTED[lang]) return html;
  return html
    .split(/(<code\b[^>]*>[\s\S]*?<\/code>|<pre\b[^>]*>[\s\S]*?<\/pre>|<tg-emoji\b[^>]*>[\s\S]*?<\/tg-emoji>)/g)
    .map(part => (/^<(?:code|pre|tg-emoji)\b/.test(part) ? part : applyDict(part, lang)))
    .join("");
}

/** Translate a button label. Only a whole-label match is translated (after
 *  stripping the icon prefix/suffix), so dynamic product names stay intact. */
export function translateLabel(text: string, lang: string): string {
  if (!text || lang === "en" || !SORTED[lang]) return text;
  const dict = DICT[lang as Exclude<Lang, "en">];
  if (!dict) return text;
  if (dict[text]) return dict[text];
  const stripped = text.replace(TG_EMOJI_RE_G, "").trim();
  const core = stripped.replace(/^[^A-Za-z0-9]+/, "").replace(/[^A-Za-z0-9]+$/, "");
  const tr = dict[core];
  if (!tr) return text;
  const lead = /^([\s\S]*?)[A-Za-z0-9]/.exec(text)?.[1] ?? "";
  const trail = /[^A-Za-z0-9]+$/.exec(text.slice(lead.length))?.[0] ?? "";
  return lead + tr + trail;
}

/** Translate every button label in a reply_markup payload. */
export function translateExtra(extra: Record<string, any>, lang: string): Record<string, any> {
  if (!extra || lang === "en") return extra;
  const markup = extra["reply_markup"];
  if (!markup) return extra;
  const key = markup.inline_keyboard ? "inline_keyboard" : markup.keyboard ? "keyboard" : null;
  if (!key) return extra;
  return {
    ...extra,
    reply_markup: {
      ...markup,
      [key]: markup[key].map((row: any[]) =>
        row.map(button =>
          typeof button === "string"
            ? translateLabel(button, lang)
            : { ...button, text: translateActionLabel(String(button.text ?? ""), String(button.callback_data ?? ""), lang) },
        ),
      ),
    },
  };
}

/** Dynamic subscription labels are translated only on their stable UI actions. */
function translateActionLabel(text: string, action: string, lang: string): string {
  if (!isLang(lang) || lang === "en") return text;
  const dict = DICT[lang];
  if (action === "tsub:pay" || action.startsWith("tsub:crypto:") || action === "tsub:buy") {
    return text.replace(/Pay from balance|Pay with USDT|Renew \+|Make my bot/g, phrase => dict[phrase] ?? phrase)
      .replace(/\b(\d+) days\b/g, (_, n) => `${n} ${PAYMENT_PHRASES[lang][2]}`);
  }
  return translateLabel(text, lang);
}
